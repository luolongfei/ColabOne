const ZH_COUNTRY_TO_CODE: Record<string, string> = {};
for (const [code, zhName] of Object.entries(
  COUNTRY_OVERRIDES_BY_LOCALE["zh-CN"],
)) {
  if (!ZH_COUNTRY_TO_CODE[zhName]) {
    ZH_COUNTRY_TO_CODE[zhName] = code;
  }
}

const displayNamesCache = new Map<ColabOneLocale, Intl.DisplayNames | null>();

function getRegionDisplayNames(
  locale: ColabOneLocale,
): Intl.DisplayNames | null {
  if (displayNamesCache.has(locale)) {
    return displayNamesCache.get(locale) || null;
  }
  const instance =
    typeof Intl !== "undefined" && typeof Intl.DisplayNames === "function"
      ? new Intl.DisplayNames([locale], { type: "region" })
      : null;
  displayNamesCache.set(locale, instance);
  return instance;
}

export function countryLabelForLocale(
  codeRaw: string,
  locale: ColabOneLocale,
  fallbackName?: string,
): string {
  const code = codeRaw.trim().toUpperCase();
  if (!code) return fallbackName || "";
  const overrides = COUNTRY_OVERRIDES_BY_LOCALE[locale];
  if (overrides && overrides[code]) return overrides[code];
  if (
    locale === "zh-CN" &&
    fallbackName &&
    fallbackName.toUpperCase() !== code
  ) {
    return fallbackName;
  }
  const intlCode = code === "UK" ? "GB" : code;
  try {
    const formatted = getRegionDisplayNames(locale)?.of(intlCode);
    if (formatted && formatted.toUpperCase() !== intlCode) return formatted;
  } catch {
    // Fallback below
  }
  if (fallbackName && fallbackName.toUpperCase() !== code) return fallbackName;
  return fallbackName || code;
}

export function translateColabOneSubregion(
  rawSubregion: string,
  locale: ColabOneLocale,
): string {
  const sub = rawSubregion.trim();
  if (!sub || locale === "zh-CN") return sub;
  return SUBREGION_TRANSLATIONS[sub]?.[locale] ?? sub;
}

export function translateColabOnePlaceName(
  rawPlace: string,
  locale: ColabOneLocale,
): string {
  const name = rawPlace.trim();
  if (!name || locale === "zh-CN") return name;
  const sub = SUBREGION_TRANSLATIONS[name]?.[locale];
  if (sub) return sub;
  const countryCode = ZH_COUNTRY_TO_CODE[name];
  if (countryCode) {
    return countryLabelForLocale(countryCode, locale, name);
  }
  return name;
}
